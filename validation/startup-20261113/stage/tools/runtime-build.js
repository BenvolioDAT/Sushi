const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.resolve(__dirname, '..');
const buildFile = 'Runtime.Build.js';
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
function inventory(directory) {
    return Object.fromEntries(fs.readdirSync(directory).filter(name => name.endsWith('.js'))
        .sort().map(name => [name, hash(fs.readFileSync(path.join(directory, name)))]));
}
function identity(directory) {
    // Normalize line endings for a stable identity across Git checkouts.
    const rows = Object.keys(inventory(directory)).filter(name => name !== buildFile)
        .map(name => [name, hash(fs.readFileSync(path.join(directory, name), 'utf8').replace(/\r\n/g, '\n'))]);
    return { id: hash(JSON.stringify(rows)), modules: rows.length + 1 };
}
function generated(build) {
    return '// Generated by npm run build; identifies runtime source, excluding this file.\n' +
        'module.exports = Object.freeze(' + JSON.stringify(build) + ');\n';
}
function prepare(directory = root) {
    const build = identity(directory), file = path.join(directory, buildFile), text = generated(build);
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
    return build;
}
function verify(directory) {
    const actual = identity(directory);
    if (fs.readFileSync(path.join(directory, buildFile), 'utf8') !== generated(actual)) throw new Error('Runtime build is stale; run npm run validate');
    return actual;
}
if (require.main === module) console.log('Runtime build ' + prepare().id);
module.exports = { root, hash, inventory, identity, prepare, verify };
